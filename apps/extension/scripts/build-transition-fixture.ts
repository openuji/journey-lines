/** Run from the repository root: node --import tsx apps/extension/scripts/build-transition-fixture.ts */
import { writeFile } from 'node:fs/promises';
import { crc32, deflateSync } from 'node:zlib';
import { loadLibav, webmEncoder } from '../../../packages/clip-webm/src/index';

function png(color: readonly number[]): Buffer {
  const width = 96;
  const height = 54;
  const chunk = (type: string, data: Buffer): Buffer => {
    const body = Buffer.concat([Buffer.from(type), data]);
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body));
    return Buffer.concat([length, body, crc]);
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header.set([8, 2, 0, 0, 0], 8);
  const row = Buffer.concat([Buffer.from([0]), ...Array.from({ length: width }, () => Buffer.from(color))]);
  const pixels = Buffer.concat(Array.from({ length: height }, () => row));
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', header), chunk('IDAT', deflateSync(pixels)), chunk('IEND', Buffer.alloc(0)),
  ]);
}

const frames = [
  { atMs: 0, png: png([255, 0, 0]) },
  { atMs: 120, png: png([0, 255, 0]) },
  { atMs: 600, png: png([0, 0, 255]) },
] as const;
const encoder = webmEncoder(await loadLibav())();
for (const frame of frames) await encoder.add(frame.png, frame.atMs);
const video = await encoder.finish(850);
const source = [
  '// Generated by scripts/build-transition-fixture.ts: red, green, blue, at uneven intervals.',
  `export const transitionFrames = ${JSON.stringify(frames.map((frame) => ({ atMs: frame.atMs, base64: frame.png.toString('base64') })), null, 2)} as const;`,
  `export const transitionVideo = ${JSON.stringify({ mimeType: video.mimeType, base64: Buffer.from(video.bytes).toString('base64') }, null, 2)} as const;`,
  '',
].join('\n');
await writeFile(new URL('../src/stories/transition-fixture.ts', import.meta.url), source);
